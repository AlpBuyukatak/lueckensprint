const assert=require('assert'),path=require('path');
const appPath=path.join(__dirname,'app.js');
delete global.window;delete global.localStorage;
delete require.cache[require.resolve(appPath)];
const seed=require(appPath).getDatabase();
const values=new Map([['lueckenSprintTextDatabase-v2',JSON.stringify(seed)]]);
global.localStorage={getItem:key=>values.has(key)?values.get(key):null,setItem:(key,value)=>values.set(key,String(value))};
global.window={addEventListener:()=>{}};global.document={addEventListener:()=>{}};
delete require.cache[require.resolve(appPath)];
const cached=require(appPath);
assert.equal(cached.restoreCachedDatabase(),true,'offline reload restores the complete cached text database immediately');
assert.equal(Object.values(cached.getDatabase()).flat().length,300,'cached reload makes all 300 texts available without fetch');
values.set('lueckenSprintTextDatabase-v2','{"invalid":true}');
assert.equal(cached.restoreCachedDatabase(),false,'invalid cache falls back cleanly to first-launch loading');
const source=require('fs').readFileSync(appPath,'utf8');
assert.ok(source.includes('TEXT_TIMEOUT_MS=6500'),'hosted JSON refresh has a timeout');
assert.ok(source.includes('refreshTextDatabaseInBackground'),'cached database refresh runs in the background');
assert.ok(source.includes('if(!ready){main.innerHTML'),'full loading state is reserved for first launch only');
assert.ok(!source.includes('await window.LueckenSync?.initialize'),'cloud sync no longer blocks the initial render');
delete global.window;delete global.localStorage;delete global.document;
console.log('Startup cache-first and offline reload tests passed');
